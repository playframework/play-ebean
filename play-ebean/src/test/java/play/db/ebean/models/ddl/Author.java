package play.db.ebean.models.ddl;

import jakarta.persistence.Entity;
import jakarta.persistence.Id;

@Entity
public class Author {
  @Id private Long id;

  private String name;

  public Long getId() {
    return id;
  }

  public String getName() {
    return name;
  }

  public void setName(String name) {
    this.name = name;
  }
}
